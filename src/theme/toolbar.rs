#[cfg(test)]
mod tests {
    use super::*;
    /// 【主题令牌测试】【原版函数】逐项对照真实 Qt 函数输出的明暗 RGBA，所有角色必须一致，无参数、无返回值
    #[test]
    fn both_palettes_match_the_actual_qt_functions() {
        let reference: serde_json::Value =
            serde_json::from_str(include_str!("../../tests/fixtures/qt-theme.json")).unwrap();
        for mode in [Mode::Light, Mode::Dark] {
            let palette = Palette::new(mode);
            let expected = &reference[mode.name()]["toolbar"];
            for (name, color) in [
                ("accent_border", palette.accent_border),
                ("accent_fill", palette.accent_fill),
                ("accent_hover_border", palette.accent_hover_border),
                ("accent_hover_fill", palette.accent_hover_fill),
                ("active_border", palette.active_border),
                ("active_fill", palette.active_fill),
                ("control_border", palette.control_border),
                ("control_fill", palette.control_fill),
                ("control_hover_fill", palette.control_hover_fill),
                ("danger_hover_border", palette.danger_hover_border),
                ("danger_hover_fill", palette.danger_hover_fill),
                ("danger_hover_text", palette.danger_hover_text),
                ("focus_border", palette.focus_border),
                ("grip_dot", palette.grip_dot),
                ("grip_dot_disabled", palette.grip_dot_disabled),
                ("grip_dot_hover", palette.grip_dot_hover),
                ("grip_hover_fill", palette.grip_hover_fill),
                ("hover_border", palette.hover_border),
                ("hover_fill", palette.hover_fill),
                ("hover_icon", palette.hover_icon),
                ("hover_text", palette.hover_text),
                ("list_border", palette.list_border),
                ("list_fill", palette.list_fill),
                ("muted_text", palette.muted_text),
                ("panel_border", palette.panel_border),
                ("panel_fill", palette.panel_fill),
                ("popup_border", palette.popup_border),
                ("popup_fill", palette.popup_fill),
                ("pressed_border", palette.pressed_border),
                ("pressed_fill", palette.pressed_fill),
                ("primary_border", palette.primary_border),
                ("primary_bottom", palette.primary_bottom),
                ("primary_hover_border", palette.primary_hover_border),
                ("primary_hover_bottom", palette.primary_hover_bottom),
                ("primary_hover_top", palette.primary_hover_top),
                ("primary_text", palette.primary_text),
                ("primary_top", palette.primary_top),
                ("selection_fill", palette.selection_fill),
                ("separator", palette.separator),
                ("slider_end", palette.slider_end),
                ("slider_groove", palette.slider_groove),
                ("slider_handle", palette.slider_handle),
                ("slider_handle_border", palette.slider_handle_border),
                (
                    "slider_handle_hover_border",
                    palette.slider_handle_hover_border,
                ),
                ("slider_start", palette.slider_start),
                ("soft_hover_border", palette.soft_hover_border),
                ("soft_hover_fill", palette.soft_hover_fill),
                ("strong_text", palette.strong_text),
                ("text", palette.text),
                ("tile_border", palette.tile_border),
                ("tile_checked_border", palette.tile_checked_border),
                ("tile_checked_bottom", palette.tile_checked_bottom),
                ("tile_checked_text", palette.tile_checked_text),
                ("tile_checked_top", palette.tile_checked_top),
                ("tile_fill", palette.tile_fill),
                ("tile_hover_border", palette.tile_hover_border),
                ("tile_hover_fill", palette.tile_hover_fill),
            ] {
                assert_eq!(
                    serde_json::json!([color.0, color.1, color.2, color.3]),
                    expected[name],
                    "{}: {name}",
                    mode.name()
                );
            }
        }
    }
}
